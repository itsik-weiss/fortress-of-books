export function getSummaryStation(id: SummaryStationId) {
  const station = summaryStations.find((item) => item.id === id);
  if (!station) throw new Error(`Unknown summary station: ${id}`);
  return station;
}

export function summaryCardsForStation(id: SummaryStationId) {
  return summaryCards.filter((card) => card.station === id);
}
