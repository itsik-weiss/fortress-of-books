export function getReviewStation(id: ReviewStationId) {
  const station = reviewStations.find((item) => item.id === id);
  if (!station) throw new Error(`Unknown review station: ${id}`);
  return station;
}

export function reviewCardsForStation(id: ReviewStationId) {
  return reviewCards.filter((card) => card.station === id);
}

export function getReviewCard(id: number) {
  return reviewCards.find((card) => card.id === id);
}
